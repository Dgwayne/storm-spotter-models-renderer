# Generates config/color_tables/ptype_refl.clr from the SAME stop list the
# app legend uses. Run: python3 scripts/gen_ptype_refl_clr.py config/color_tables/ptype_refl.clr
# (lib/data/weather_models/precip_type_refl.dart kPtypeReflRampStops).
import sys
RAMPS = {
 1: [(0,0x9EE39A),(10,0x5FCF5A),(20,0x2DB02D),(30,0x17892A),(40,0x0E6E1A),(50,0xE8E23A),(60,0xE0B814),(75,0xC9A70C)],
 2: [(0,0x9CC9F5),(10,0x6AA8F0),(20,0x3F80E6),(30,0x2A5AD0),(40,0x2A2FA8),(50,0x5A1B9C),(75,0xB04CE0)],
 3: [(0,0xF5B5E8),(15,0xE98AD6),(30,0xD24BBF),(45,0xA3229A),(75,0x70106E)],
 4: [(0,0xFFC4A0),(15,0xFF9A5C),(30,0xFF5A1F),(45,0xD4210F),(75,0x8F0A0A)],
}
A0, FADE = 170, 10
def at(stops, d):
    for (d0,c0),(d1,c1) in zip(stops,stops[1:]):
        if d0 <= d <= d1:
            f=(d-d0)/(d1-d0)
            return tuple(round(((c0>>s)&255)+(((c1>>s)&255)-((c0>>s)&255))*f) for s in (16,8,0))
    return tuple((stops[-1][1]>>s)&255 for s in (16,8,0))
L=["# Reflectivity + Precip Type (ptypeRefl / ptypeRefl15). GENERATED by",
"# scripts/gen_ptype_refl_clr.py from the app's kPtypeReflRampStops (precip_type_refl.dart): edit",
"# both together. value = 100 * type + dBZ (0..75): rain 100s, snow 200s,",
f"# sleet 300s, freezing rain 400s. Alpha {A0} at 0 dBZ, full by {FADE} dBZ.",
"# Use with gdaldem color-relief -alpha WITHOUT -nearest_color_entry.",
"# gdaldem rejects inline comments on data rows - keep them bare.",
"nv     0   0   0   0","0      0   0   0   0","99.99  0   0   0   0"]
for t,st in RAMPS.items():
    pts=sorted(set([d for d,_ in st]+[FADE]))
    for d in pts:
        r,g,b=at(st,d); a=round(A0+(255-A0)*min(d,FADE)/FADE)
        L.append(f"{100*t+d:<6g} {r:>3} {g:>3} {b:>3} {a:>3}")
    L.append(f"{100*t+75.01:<6g}   0   0   0   0")
    if t<4: L.append(f"{100*t+99.99:<6g}   0   0   0   0")
open(sys.argv[1],'w',newline='\n').write("\n".join(L)+"\n")
